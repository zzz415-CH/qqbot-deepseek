def set_font(run, size=11, bold=False, color=None, cn=CN, en=EN, italic=False):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    run.font.name = en
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:ascii"), en)
    rFonts.set(qn("w:hAnsi"), en)
    rFonts.set(qn("w:eastAsia"), cn)
    if color:
        run.font.color.rgb = RGBColor.from_string(color)


def para_style(p, before=0, after=6, line=1.45, align=None, indent=None,
               first=None, keep_next=False):
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line
    pf.widow_control = True
    if align is not None:
        pf.alignment = align
    if indent is not None:
        pf.left_indent = Cm(indent)
    if first is not None:
        pf.first_line_indent = Cm(first)
    if keep_next:
        pf.keep_with_next = True


def inline(p, text, size=10.5, color="1F2A2E", bold_color=None):
    """**粗体** 语法解析。"""
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        if i % 2 == 1:
            r = p.add_run(seg)
            set_font(r, size=size, bold=True, color=bold_color or DARK)
        else:
            r = p.add_run(seg)
            set_font(r, size=size, color=color)
    return p


def shade(el, fill):
    """给 pPr 或 tcPr 加底纹。"""
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    el.append(shd)


def p_border(p, left=None, bottom=None, size=18):
    pPr = p._p.get_or_add_pPr()
    bdr = OxmlElement("w:pBdr")
    if left:
        e = OxmlElement("w:left")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), str(size))
        e.set(qn("w:space"), "8")
        e.set(qn("w:color"), left)
        bdr.append(e)
    if bottom:
        e = OxmlElement("w:bottom")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), str(size))
        e.set(qn("w:space"), "4")
        e.set(qn("w:color"), bottom)
        bdr.append(e)
    pPr.append(bdr)


