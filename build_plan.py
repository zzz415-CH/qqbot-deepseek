def numbered(items, size=10.4):
    for i, t in enumerate(items, 1):
        p = doc.add_paragraph()
        r = p.add_run("%d. " % i)
        set_font(r, size=size, bold=True, color=ORANGE)
        inline(p, t, size=size)
        para_style(p, after=4, indent=0.6, first=-0.6, line=1.45)


def callout(title, text, tone="orange"):
    bg = WARN_BG if tone == "orange" else LIGHT
    line = ORANGE if tone == "orange" else TEAL
    p = doc.add_paragraph()
    r = p.add_run(("⚠  " if tone == "orange" else "◆  ") + title)
    set_font(r, size=10.5, bold=True, color=line)
    p.paragraph_format.space_before = Pt(9)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.left_indent = Cm(0.3)
    p.paragraph_format.keep_with_next = True
    p.paragraph_format.keep_together = True
    pPr = p._p.get_or_add_pPr()
    shade(pPr, bg)
    bdr = OxmlElement("w:pBdr")
    e = OxmlElement("w:left")
    e.set(qn("w:val"), "single")
    e.set(qn("w:sz"), "24")
    e.set(qn("w:space"), "6")
    e.set(qn("w:color"), line)
    bdr.append(e)
    pPr.append(bdr)
    p2 = doc.add_paragraph()
    inline(p2, text, size=10.3)
    para_style(p2, after=9, indent=0.3, line=1.45)
    p2.paragraph_format.keep_together = True
    p2.paragraph_format.widow_control = True
    pPr2 = p2._p.get_or_add_pPr()
    shade(pPr2, bg)
    bdr2 = OxmlElement("w:pBdr")
    e2 = OxmlElement("w:left")
    e2.set(qn("w:val"), "single")
    e2.set(qn("w:sz"), "24")
    e2.set(qn("w:space"), "6")
    e2.set(qn("w:color"), line)
    bdr2.append(e2)
    pPr2.append(bdr2)
    return p


def cell_text(cell, text, size=9.2, bold=False, color="1F2A2E", align=None):
    cell.text = ""
    p = cell.paragraphs[0]
    inline(p, text, size=size, color=color)
    para_style(p, before=1.5, after=1.5, line=1.3)
    if align is not None:
        p.alignment = align
    if bold:
        for r in p.runs:
            r.font.bold = True
    cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER


def cm2tw(v):
    """厘米 -> twips（1 cm = 567 twips）"""
    try:
        cm = v.cm
    except AttributeError:
        cm = v
    return int(round(cm * 567))


def set_tcwidth(cell, width):
    tcPr = cell._tc.get_or_add_tcPr()
    for el in tcPr.findall(qn("w:tcW")):
        tcPr.remove(el)
    tcW = OxmlElement("w:tcW")
    tcW.set(qn("w:type"), "dxa")
    tcW.set(qn("w:w"), str(cm2tw(width)))
    tcPr.append(tcW)


def table(headers, rows, widths, size=9.2, head_bg=DARK, band=True, first_col_bold=True,
          keep_rows=True):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    tblPr = t._tbl.tblPr
    for tag in ("w:tblW", "w:tblLayout"):
        for el in tblPr.findall(qn(tag)):
            tblPr.remove(el)
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    tblPr.append(layout)
    tblW = OxmlElement("w:tblW")
    tblW.set(qn("w:type"), "dxa")
    tblW.set(qn("w:w"), str(sum(cm2tw(w) for w in widths)))
    tblPr.append(tblW)
    # 表格级单元格左右边距收紧，避免窄列被挤压
    mar = OxmlElement("w:tblCellMar")
    for side, val in (("top", 30), ("left", 70), ("bottom", 30), ("right", 70)):
        e = OxmlElement("w:" + side)
        e.set(qn("w:w"), str(val))
        e.set(qn("w:type"), "dxa")
        mar.append(e)
    tblPr.append(mar)
    # 显式列宽网格
    grid = OxmlElement("w:tblGrid")
    for w in widths:
        gc = OxmlElement("w:gridCol")
        gc.set(qn("w:w"), str(cm2tw(w)))
        grid.append(gc)
    t._tbl.insert(1, grid)
    # 表格整体边框转浅色
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement("w:" + edge)
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4")
        e.set(qn("w:space"), "0")
        e.set(qn("w:color"), "C7D6D8")
        borders.append(e)
    tblPr.append(borders)
    # 表头
    hdr = t.rows[0]
    trPr = hdr._tr.get_or_add_trPr()
    th = OxmlElement("w:tblHeader")
    trPr.append(th)
    for i, htxt in enumerate(headers):
        c = hdr.cells[i]
        set_tcwidth(c, widths[i])
        cell_text(c, htxt, size=size, bold=True, color=WHITE)
        for p in c.paragraphs:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        tcPr = c._tc.get_or_add_tcPr()
        shade(tcPr, head_bg)
    # 数据行
    for ri, row in enumerate(rows):
        tr = t.add_row()
        if keep_rows:
            trPr2 = tr._tr.get_or_add_trPr()
            cs = OxmlElement("w:cantSplit")
            trPr2.append(cs)
        cells = tr.cells
        for i, val in enumerate(row):
            c = cells[i]
            set_tcwidth(c, widths[i])
            cell_text(c, val, size=size, color="1F2A2E")
            if first_col_bold and i == 0:
                for p in c.paragraphs:
                    for r in p.runs:
                        r.font.bold = True
                        r.font.color.rgb = RGBColor.from_string(DARK)
            if band and ri % 2 == 1:
                shade(c._tc.get_or_add_tcPr(), LIGHT)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


